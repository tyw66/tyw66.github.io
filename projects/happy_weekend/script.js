const resultDom = document.getElementById('result');
const pickBtn = document.getElementById('pickBtn');
const baikeBtn = document.getElementById('baikeBtn');

let currentPlace = '';

pickBtn.onclick = function() {
    const randomIndex = Math.floor(Math.random() * placeList.length);
    const selectedPlace = placeList[randomIndex];
    currentPlace = selectedPlace;
    resultDom.textContent = selectedPlace;
}

baikeBtn.onclick = function() {
    if (!currentPlace) {
        resultDom.textContent = '请先抽取一个地点';
        return;
    }
    // 去掉地名中括号及其内容（如"丹景台（城市之眼）"→"丹景台"），以匹配百科词条名
    const name = currentPlace.replace(/（[^）]*）/g, '').trim();
    window.open('https://baike.baidu.com/item/' + encodeURIComponent(name), '_blank');
}
